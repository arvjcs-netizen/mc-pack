def end_sky():
    img = Image.new("RGBA", (128, 128), (60, 52, 90, 255))
    p = img.load()
    n = fbm(128, 128, 9, cells=(32, 16, 8), weights=(0.5, 0.3, 0.2))
    rng = random.Random(9)
    for y in range(128):
        for x in range(128):
            p[x, y] = (*mix((50, 40, 80), (90, 70, 130), n[y][x]), 255)
    for _ in range(60):
        p[rng.randrange(128), rng.randrange(128)] = (220, 210, 255, 255)
    return img


# ---------------------------------------------------------------- particles (8px cells on a 128x128 sheet)
def cell(img, idx, sprite_img):
    x, y = (idx % 16) * 8, (idx // 16) * 8
    img.alpha_composite(sprite_img, (x, y))


def disc(r, c, soft=True, cx=3.5, cy=3.5, size=8):
    s = new(size, size)
    for y in range(size):
        for x in range(size):
            d = math.hypot(x - cx, y - cy)
            if d <= r:
                v = 1 - (d / max(r, 0.01)) * 0.35 if soft else 1
                put(s, x, y, tuple(round(ch * v) for ch in c))
    return s


