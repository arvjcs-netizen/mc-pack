def rune(seed, w=5, h=7):
    rng = random.Random(seed)
    s = new(8, 8)
    p = s.load()
    x, y = rng.randrange(w), 0
    pts = [(rng.randrange(w), rng.randrange(h)) for _ in range(3)]
    line(p, (rng.randrange(w), 0), pts[0], (255, 255, 255), 8, 8)
    line(p, pts[0], pts[1], (255, 255, 255), 8, 8)
    if rng.random() < 0.7:
        line(p, pts[1], (rng.randrange(w), h - 1), (255, 255, 255), 8, 8)
    if rng.random() < 0.5:
        p[rng.randrange(w), rng.randrange(h)] = (255, 255, 255, 255)
    return s


