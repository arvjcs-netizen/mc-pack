def painting(w, h, seed):
    rng = random.Random(seed)
    a, b, c = PALETTES[seed % len(PALETTES)]
    style = seed % 4
    img = new(w, h)
    p = img.load()
    for y in range(h):
        for x in range(w):
            u, v = x / w, y / h
            if style == 0:          # sunset over waves
                horizon = 0.6 + 0.04 * math.sin(u * 6.28 * 2 + seed)
                if v < horizon:
                    col = mix(c, b, v / horizon)
                    if math.hypot(u - 0.65, (v - horizon + 0.05) * w / h) < 0.16:
                        col = c
                else:
                    col = mix(b, a, (v - horizon) / (1 - horizon))
                    if int((x + y * 3 + seed) % 7) == 0:
                        col = mix(col, c, 0.4)
            elif style == 1:        # mountains
                ridge = 0.45 + 0.18 * math.sin(u * 6.28 * 1.5 + seed) + 0.08 * math.sin(u * 6.28 * 4 + seed * 2)
                col = mix(c, b, v) if v < ridge else mix(a, b, 0.3 * (1 - v))
                if v > ridge and v < ridge + 0.06:
                    col = mix(col, (240, 240, 250), 0.6)
            elif style == 2:        # concentric rings
                d = math.hypot(u - 0.5, (v - 0.5) * h / w)
                col = [a, b, c][int(d * 12 + seed) % 3]
            else:                   # tiles
                col = [a, b, c][(x // max(2, w // 8) + y // max(2, h // 8) + seed) % 3]
            p[x, y] = (*col, 255)
    for x in range(w):
        p[x, 0] = (*INK, 255)
        p[x, h - 1] = (*INK, 255)
    for y in range(h):
        p[0, y] = (*INK, 255)
        p[w - 1, y] = (*INK, 255)
    return img


