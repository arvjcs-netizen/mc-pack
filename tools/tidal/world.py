def colormap(foliage=False):
    """x = 1 - temperature, y = 1 - rainfall*temperature (lower-left triangle is used)."""
    hot_wet = (54, 176, 62) if not foliage else (40, 150, 46)
    hot_dry = (196, 186, 84) if not foliage else (170, 160, 60)
    cold = (110, 168, 150) if not foliage else (90, 146, 130)
    img = new(256, 256)
    p = img.load()
    for y in range(256):
        for x in range(256):
            t = 1 - x / 255
            r = (1 - y / 255) / max(t, 1e-3)
            r = min(1, r)
            c = mix(mix(hot_dry, hot_wet, r), cold, 1 - t)
            p[x, y] = (*c, 255)
    return img


