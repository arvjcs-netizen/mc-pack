def put(img, x, y, c, a=255):
    p = img.load()
    if 0 <= x < img.size[0] and 0 <= y < img.size[1]:
        p[x, y] = (*c[:3], a)


# ---------------------------------------------------------------- sky
def sun():
    img = new(32, 32)
    for y in range(32):
        for x in range(32):
            d = math.hypot(x - 15.5, y - 15.5)
            if d < 6:
                put(img, x, y, (255, 250, 220) if d < 4.5 else (255, 230, 150))
            elif d < 9 and (abs(x - 15.5) < 1.2 or abs(y - 15.5) < 1.2 or abs(abs(x - 15.5) - abs(y - 15.5)) < 1.0):
                put(img, x, y, (255, 214, 110))
    return img


def moon_phases():
    """8 phases (0 full -> 4 new -> 7). Lit part: right of the terminator while waning, left while waxing."""
    img = new(128, 64)
    for i in range(8):
        ox, oy = (i % 4) * 32, (i // 4) * 32
        k = math.cos(i / 8 * 2 * math.pi)
        for y in range(32):
            for x in range(32):
                dx, dy = x - 15.5, y - 15.5
                if math.hypot(dx, dy) >= 6.5:
                    continue
                hw = math.sqrt(max(0.0, 6.5 ** 2 - dy * dy))
                lit = dx > -hw * k if i <= 4 else dx < hw * k
                c = (230, 236, 250) if lit else (52, 62, 90)
                if lit and (x * 7 + y * 3) % 13 == 0:
                    c = (196, 206, 226)
                put(img, ox + x, oy + y, c)
    return img


def clouds():
    n = fbm(256, 256, 5, cells=(16, 8, 4), weights=(0.55, 0.3, 0.15))
    img = new(256, 256)
    p = img.load()
    for y in range(256):
        for x in range(256):
            # chunky cloud cells (the game samples 1 texel per 12 blocks), so quantize to 1px blobs
            if n[y][x] > 0.64:
                p[x, y] = (255, 255, 255, 255)
    return img


def rain():
    img = new(64, 256)
    rng = random.Random(3)
    for _ in range(90):
        x, y = rng.randrange(64), rng.randrange(256)
        ln = rng.randint(5, 10)
        for k in range(ln):
            put(img, x, (y + k) % 256, (150, 190, 240), 200 - k * 12)
    return img


def snow():
    img = new(64, 256)
    rng = random.Random(4)
    for _ in range(120):
        x, y = rng.randrange(1, 63), rng.randrange(1, 255)
        put(img, x, y, (255, 255, 255))
        if rng.random() < 0.4:
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                put(img, x + dx, y + dy, (220, 232, 250), 200)
