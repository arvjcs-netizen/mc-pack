def glyph_rows(ch):
    if ch in F:
        return F[ch]
    if ch in EXTRA:
        return EXTRA[ch]
    if ch in DECOMP:
        base, acc = DECOMP[ch]
        rows = list(glyph_rows(base))
        if acc is None:                                     # cedilla: a hook under the letter
            rows = rows + ["." * len(rows[0])] * (7 - len(rows))
            rows = rows[:7] + ["..#" + "." * (len(rows[0]) - 3)]
            return rows
        a = ACCENTS[acc]
        w = max(len(rows[0]), len(a[0]))
        if base.isupper() or base == "I":
            body = rows[:3] + rows[4:]                     # drop a middle row to make room
            body = body[1:] if len(a) > 1 else body
            top = [r.center(w, ".") for r in a]
            out = top + [r.ljust(w, ".") for r in body]
            return out[:8]
        top = [r.center(w, ".") for r in a][:2]
        body = rows[2:]
        return ([top[0], top[1] if len(top) > 1 else "." * w] + [r.ljust(w, ".") for r in body])[:8]
    return None


def draw_glyph(img, code, rows):
    ox, oy = (code % 16) * 8, (code // 16) * 8
    for y, row in enumerate(rows[:8]):
        for x, c in enumerate(row[:8]):
            if c == "#":
                put(img, ox + x, oy + y, (255, 255, 255))


def box_glyph(img, code, ch):
    ox, oy = (code % 16) * 8, (code // 16) * 8
    p = img.load()
    if ch in "░▒▓":
        k = "░▒▓".index(ch)
        for y in range(8):
            for x in range(8):
                if (k == 0 and (x + y * 2) % 4 == 0) or (k == 1 and (x + y) % 2 == 0) or (k == 2 and (x + y * 2) % 4 != 0):
                    p[ox + x, oy + y] = (255, 255, 255, 255)
        return
    if ch in "█▄▌▐▀":
        for y in range(8):
            for x in range(8):
                on = {"█": True, "▄": y >= 4, "▌": x < 4, "▐": x >= 4, "▀": y < 4}[ch]
                if on:
                    p[ox + x, oy + y] = (255, 255, 255, 255)
        return
    up, down, left, right = BOX[ch]
    cx, cy = 3, 3

    def vline(y0, y1, kind):
        xs = (cx,) if kind == 1 else (cx - 1, cx + 1)
        for x in xs:
            for y in range(y0, y1 + 1):
                p[ox + x, oy + y] = (255, 255, 255, 255)

    def hline(x0, x1, kind):
        ys = (cy,) if kind == 1 else (cy - 1, cy + 1)
        for y in ys:
            for x in range(x0, x1 + 1):
                p[ox + x, oy + y] = (255, 255, 255, 255)

    if up:
        vline(0, cy + (1 if up == 2 else 0), up)
    if down:
        vline(cy - (1 if down == 2 else 0), 7, down)
    if left:
        hline(0, cx + (1 if left == 2 else 0), left)
    if right:
        hline(cx - (1 if right == 2 else 0), 7, right)


def font():
    img = new(128, 128)
    for code in range(256):
        if 32 < code < 127:
            ch = chr(code)
        elif code < len(LOW):
            ch = LOW[code]
        elif 128 <= code < 128 + len(HIGH):
            ch = HIGH[code - 128]
        else:
            continue
        if ch in BOX or ch in "░▒▓█▄▌▐▀":
            box_glyph(img, code, ch)
            continue
        rows = glyph_rows(ch)
        if rows:
            draw_glyph(img, code, rows)
    return img


def font_sga():
    img = new(128, 128)
    for code in range(33, 127):
        g = RUNES[code % len(RUNES)] if chr(code).isalpha() else None
        if g is None:
            rows = F.get(chr(code))
            if rows:
                draw_glyph(img, code, rows)
            continue
        img.alpha_composite(g, ((code % 16) * 8, (code // 16) * 8))
    return img


